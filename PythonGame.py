def print_line():
    print("\n" + "=" * 68)


def show_status():
    cfg = LEVEL_CONFIGS[player["level"] - 1]
    print_line()
    print(f"УРОВЕНЬ {cfg[0]}: {cfg[1]} | Сектор: {cfg[2]} | Угроза: {cfg[3]}")
    inf_status = "ЗАРАЖЕН (G-вирус)" if player["infected"] else "Здоров"
    print(f"ГЕРОЙ: {player['name']} | HP: {player['hp']}/{player['max_hp']} | Статус: {inf_status}")
    print(f"ИНВЕНТАРЬ ({len(inventory)}): {', '.join(inventory) if inventory else 'Пусто'}")
    print_line()


def show_help():
    print("\n--- ОБЩИЕ КОМАНДЫ ---")
    print("  осмотреть         - изучить текущую локацию")
    print("  действия (д)      - показать список доступных сейчас действий/команд")
