# 4. УРОВЕНЬ 1: ГЛАВНЫЙ ХОЛЛ R.P.D. (Множества и поиск ключей)
# ==============================================================================
def level_1_hall():
    show_status()
    print("СЮЖЕТ: Вы заперты в холле участка R.P.D. Чтобы открыть тайный проход под")
    print("статуей Богини, нужно собрать и вставить в нее 3 уникальные медали.")

    room_items = ["патроны", "медаль льва", "красная трава"]
    required_medals = {"медаль льва", "медаль девы", "медаль единорога"}
    inserted_medals = set()

    while True:
        check_alive()
        cmd = input("\n[Уровень 1 - Холл] Команда: ").strip().lower()
        if process_base_command(cmd, room_items):
            continue

        if cmd == "осмотреть":
            print(f"\nПредметы в комнате (на стойке и полу): {', '.join(room_items) if room_items else 'пусто'}")
            print(">> Подсказка: Золотая 'медаль льва' лежит прямо перед вами на стойке администратора!")
            print("   Заберите ее командой: взять медаль льва")
            print("   Введите 'действия' (или 'д'), чтобы увидеть все доступные команды.")
            if "проход_1" in unlocked_doors:
                print("Путь открыт! Введите [идти дальше] для перехода на Уровень 2.")
        elif cmd == "читать памятку":
            print(">> Памятка: 'Код сейфа: год создания отряда S.T.A.R.S. (1996) + 240 = 2236'.")
        elif cmd == "обыскать стол":
            if "стол" not in solved_puzzles:
                print(">> Вы ломаете замок ящика! Найдена 'медаль девы' (возьмите ее командой 'взять').")
                room_items.append("медаль девы")
                solved_puzzles.add("стол")
            else:
                print(">> Ящик стола уже пуст.")
        elif cmd == "открыть сейф":
            if "сейф" in solved_puzzles:
                print(">> Сейф уже открыт.")
            elif input("Введите 4-значный код сейфа: ").strip() == SECURITY_CODES["сейф"]:
                print(">> Сейф открыт! Получены 'медаль единорога' и 'зажигалка'.")
                inventory.extend(["медаль единорога", "зажигалка"])
                solved_puzzles.add("сейф")
            else:
                player["hp"] -= 15
                print(">> Неверный код! Сработала электро-защита (-15 HP).")
        elif cmd == "вставить медали":
            found = set(inventory).intersection(required_medals)
            if not found:
                print(">> В вашем инвентаре сейчас нет медалей.")
                continue
            for medal in found:
                inventory.remove(medal)
                inserted_medals.add(medal)
                print(f">> Вы вставили '{medal}' в разъем статуи.")
            print(f">> Установлено медалей: {len(inserted_medals)}/3.")
            if required_medals.issubset(inserted_medals):
                print(">> Механизм сработал! Статуя открывает проход на Уровень 2!")
                unlocked_doors.add("проход_1")
        elif cmd == "идти дальше" and "проход_1" in unlocked_doors:
            player["level"] = 2
            break
        else:
            print(">> Неизвестная команда или проход закрыт. Введите 'осмотреть' или 'действия'.")


