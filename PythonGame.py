def level_4_lab():
    player["infected"] = True
    show_status()
    print("СЮЖЕТ: При сходе с фуникулера вас ранил мутант Биркин — вы ЗАРАЖЕНЫ G-вирусом!")
    print("Создайте вакцину в терминале, возьмите ракетницу со стойки и уничтожьте Тирана!")

    # Ракетница теперь лежит прямо в комнате на оружейной стойке
    room_items = ["аптечка", "ракетница"]
    quiz = {
        "Какой вирус вызвал зомби-эпидемию в городе? (т-вирус / лас-плагас)": "т-вирус",
        "Название корпорации, создавшей био-оружие? (амбрелла / трайселл)": "амбрелла",
        "Что получается при смешивании зеленой и красной травы? (аптечка / спрей)": "аптечка"
    }
    tyrant_alive = True

    while True:
        check_alive()
        cmd = input("\n[Уровень 4 - Лаборатория] Команда: ").strip().lower()
        if process_base_command(cmd, room_items):
            continue

        if cmd == "осмотреть":
            print(f"\nПредметы в зале (на стойке): {', '.join(room_items) if room_items else 'пусто'}")
            print(">> Подсказка: Противотанковая 'ракетница' лежит на стойке. Подберите ее: взять ракетница")
            print("Введите 'действия' (или 'д'), чтобы посмотреть список доступных команд.")
        elif cmd == "терминал":
            if not player["infected"]:
                print(">> Вы уже излечились от вируса.")
                continue
            score = sum(1 for q, a in quiz.items() if input(f"{q}\nОтвет: ").strip().lower() == a)
            if score == len(quiz):
                player["infected"] = False
