import sys

# ==============================================================================
# 1. ГЛОБАЛЬНЫЕ КОЛЛЕКЦИИ ДАННЫХ (КОРТЕЖИ И СЛОВАРИ)
# ==============================================================================
# КОРТЕЖИ (Tuples) - неизменяемые настройки: (Номер, Локация, Координаты, Угроза)
LEVEL_CONFIGS = (
    (1, "Главный холл участка R.P.D.", (10, 25), "Низкий"),
    (2, "Западный коридор и Офис S.T.A.R.S.", (14, 30), "Средний"),
    (3, "Подземная парковка и Канализация", (5, 5), "Высокий"),
    (4, "Секретная лаборатория NEST", (0, 0), "Критический")
)

# СЛОВАРЬ (Dict) - база данных предметов и их описаний
ITEMS_DB = {
    "пистолет": "Табельный пистолет Матильда. Эффективен против обычных зомби.",
    "патроны": "Коробка патронов 9мм для пистолета.",
    "зеленая трава": "Лечебная трава из R.P.D. Восстанавливает 35 HP.",
    "красная трава": "Усиливает лечебный эффект зеленой травы при смешивании.",
    "аптечка": "Смесь трав. Полностью восстанавливает здоровье (100 HP).",
    "медаль льва": "Золотая медаль с профилем льва для статуи Богини.",
    "медаль девы": "Старинная бронзовая медаль с рельефом девы.",
    "медаль единорога": "Медаль с изображением мифического единорога.",
    "зажигалка": "Бензиновая зажигалка с гербом полиции Раккун-Сити.",
    "дробовик": "Помповое ружье W-870. Смертельно для Лизунов.",
    "болтрез": "Тяжелый инструмент для перекусывания стальных цепей.",
    "вентиль": "Чугунный шестигранный вентиль для паровых труб.",
    "синяя колба": "Стеклянная капсула с базовым химическим реагентом.",
    "красная колба": "Капсула с термоактивным реагентом.",
    "фиолетовая колба": "Синтезированный реагент для допуска к фуникулеру.",
    "вакцина": "Экспериментальный антивирус против G-вируса.",
    "ракетница": "Противотанковая ракетница с одним зарядом. Убивает Тирана."
}

# СЛОВАРИ кодов безопасности и рецептов крафта (ключи рецептов - КОРТЕЖИ)
SECURITY_CODES = {"сейф": "2236", "шкафчик": "CAP"}
CRAFT_RECIPES = {
    ("зеленая трава", "красная трава"): "аптечка",
    ("красная колба", "синяя колба"): "фиолетовая колба"
}

# ==============================================================================
# 2. СОСТОЯНИЕ ИГРОКА И МИРА (СЛОВАРЬ, СПИСКИ, МНОЖЕСТВА)
# ==============================================================================
player = {
    "name": "",
    "hp": 100,
    "max_hp": 100,
    "level": 1,
    "infected": False
}

# СПИСОК (List) - инвентарь игрока
inventory = ["пистолет", "зеленая трава"]

# МНОЖЕСТВА (Sets) - уникальные открытые двери, решенные загадки и убитые враги
unlocked_doors = set()
solved_puzzles = set()
defeated_enemies = set()

# СЛОВАРЬ СПИСКОВ - предметы, находящиеся на каждом уровне
level_items = {
    1: ["патроны", "медаль льва", "красная трава"],
    2: ["зеленая трава", "патроны"],
    3: ["синяя колба", "зеленая трава"],
    4: ["аптечка", "ракетница"]
}

# Специфические коллекции для задач на уровнях
required_medals = {"медаль льва", "медаль девы", "медаль единорога"}
inserted_medals = set()
enemies_lvl2 = ["зомби-полицейский", "лизун"]
correct_torches = ["северный", "южный", "восточный"]
valves_lvl3 = {"труба 1": True, "труба 2": False, "труба 3": True}
quiz_lvl4 = {
    "Какой вирус вызвал зомби-эпидемию в городе? (т-вирус / лас-плагас)": "т-вирус",
    "Название корпорации, создавшей био-оружие? (амбрелла / трайселл)": "амбрелла",
    "Что получается при смешивании зеленой и красной травы? (аптечка / спрей)": "аптечка"
}
tyrant_alive = True

# ==============================================================================
# 3. СТАРТ ИГРЫ И ВВОД ИМЕНИ (ЦИКЛ ПО УСЛОВИЮ)
# ==============================================================================
print("\n" + "=" * 68)
print("   RESIDENT EVIL: RACCOON CITY ESCAPE (ТЕКСТОВАЯ НОВЕЛЛА)   ")
print("=" * 68)

while player["name"] == "":
    entered_name = input("Введите имя вашего героя: ").strip()
    if entered_name != "":
        player["name"] = entered_name
    else:
        print(">> Ошибка: имя не может быть пустым! Пожалуйста, введите имя.")

print(f"\nДобро пожаловать в кошмар Раккун-Сити, {player['name']}!")
print("Подсказка: в любой момент вводите 'действия' (или 'д') для списка команд.")

# ==============================================================================
# 4. ГЛАВНЫЙ ИГРОВОЙ ЦИКЛ (БЕЗ WHILE TRUE И БЕЗ DEF)
# ==============================================================================
game_active = True
level_announced = 0

while game_active and player["hp"] > 0:
    current_lvl = player["level"]
    room_items = level_items[current_lvl]

    # Вывод описания уровня при первом входе на него через match/case
    if level_announced != current_lvl:
        cfg = LEVEL_CONFIGS[current_lvl - 1]
        print("\n" + "=" * 68)
        print(f"УРОВЕНЬ {cfg[0]}: {cfg[1]} | Сектор: {cfg[2]} | Угроза: {cfg[3]}")
        print("=" * 68)
        match current_lvl:
            case 1:
                print("СЮЖЕТ: Вы заперты в холле участка R.P.D. Чтобы открыть тайный проход")
                print("под статуей Богини, нужно собрать и вставить в нее 3 уникальные медали.")
            case 2:
                print("СЮЖЕТ: В коридоре монстры, а путь на парковку закрыт решеткой.")
                print("Найдите оружие, зачистите коридор и зажгите 3 факела в верном порядке.")
            case 3:
                print("СЮЖЕТ: Проход к фуникулеру прегражден паром из прорванных труб.")
                print("Перекройте пар вентилем и смешайте реагенты в 'фиолетовая колба'.")
            case 4:
                player["infected"] = True
                print("СЮЖЕТ: При сходе с фуникулера вас ранил Биркин — вы ЗАРАЖЕНЫ G-вирусом!")
                print("Создайте вакцину в терминале, возьмите ракетницу и убейте Тирана Т-103!")
        level_announced = current_lvl

    cmd = input(f"\n[Уровень {current_lvl}] Введите команду: ").strip().lower()

    # Разделение команды для удобной проверки через switch-case (match-case)
    parts = cmd.split(" ", 1)
    verb = parts[0]
    arg = parts[1].strip() if len(parts) > 1 else ""

    # --------------------------------------------------------------------------
    # БЛОК 1: ОБРАБОТКА ОБЩИХ КОМАНД ЧЕРЕЗ SWITCH-CASE (MATCH / CASE)
    # --------------------------------------------------------------------------
    command_handled = True

    match verb:
        case "помощь":
            print("\n--- ОБЩИЕ КОМАНДЫ ---")
            print("  осмотреть         - изучить текущую локацию и предметы")
            print("  действия (или д)  - показать все доступные сейчас команды")
            print("  взять <предмет>   - подобрать предмет из комнаты в инвентарь")
            print("  инфо <предмет>    - прочитать описание предмета из словаря")
            print("  лечиться          - использовать 'зеленая трава' или 'аптечка'")
            print("  смешать           - объединить два предмета из инвентаря")
            print("  статус            - показать здоровье, статус и инвентарь")
            print("  выход             - завершить игру")

        case "статус":
            cfg = LEVEL_CONFIGS[current_lvl - 1]
            inf_text = "ЗАРАЖЕН (G-вирус)" if player["infected"] else "Здоров"
            print("\n" + "-" * 68)
            print(f"ЛОКАЦИЯ: {cfg[1]} | Координаты: {cfg[2]}")
            print(f"ГЕРОЙ: {player['name']} | HP: {player['hp']}/{player['max_hp']} | Статус: {inf_text}")
            print(f"ИНВЕНТАРЬ ({len(inventory)}): {', '.join(inventory) if inventory else 'Пусто'}")
            print("-" * 68)

        case "действия" | "д":
            print(f"\n--- ДОСТУПНЫЕ ДЕЙСТВИЯ НА УРОВНЕ {current_lvl} ---")
            print("• Общие: [осмотреть], [действия], [взять <предмет>], [инфо <предмет>], [лечиться], [смешать], [статус]")
            if current_lvl == 1:
                print("• Сюжетные: [читать памятку], [обыскать стол], [открыть сейф], [вставить медали]")
                if "проход_1" in unlocked_doors:
                    print("• Переход: [идти дальше] (проход под статуей открыт!)")
            elif current_lvl == 2:
                print("• Сюжетные: [читать дневник], [открыть шкафчик], [атаковать], [зажечь факелы]")
                if "проход_2" in unlocked_doors:
                    print("• Переход: [идти дальше] (решетка поднята!)")
            elif current_lvl == 3:
                print("• Сюжетные: [читать записку], [срезать цепь], [перекрыть пар], [сканировать]")
                if "проход_3" in unlocked_doors:
                    print("• Переход: [идти дальше] (двери фуникулера открыты!)")
            elif current_lvl == 4:
                print("• Финальные: [терминал], [бой с тираном], [эвакуация]")

        case "лечиться":
            if "аптечка" in inventory:
                inventory.remove("аптечка")
                player["hp"] = player["max_hp"]
                print(">> Вы использовали аптечку. Здоровье полностью восстановлено (100 HP)!")
            elif "зеленая трава" in inventory:
                inventory.remove("зеленая трава")
                player["hp"] = min(player["max_hp"], player["hp"] + 35)
                print(f">> Вы использовали зеленую траву. Текущее здоровье: {player['hp']} HP.")
            else:
                print(">> В инвентаре нет лечебных средств ('зеленая трава' или 'аптечка').")

        case "смешать":
            print("Ваш инвентарь:", ", ".join(inventory))
            item1 = input("Первый предмет для смешивания: ").strip().lower()
            item2 = input("Второй предмет для смешивания: ").strip().lower()
            if item1 not in inventory or item2 not in inventory or item1 == item2:
                print(">> Ошибка: нужны два разных предмета из вашего инвентаря.")
            else:
                recipe_key = tuple(sorted([item1, item2]))
                if recipe_key in CRAFT_RECIPES:
                    result = CRAFT_RECIPES[recipe_key]
                    inventory.remove(item1)
                    inventory.remove(item2)
                    inventory.append(result)
                    print(f">> УСПЕХ! Вы скомбинировали предметы и получили: '{result}'!")
                else:
                    print(">> Эти предметы нельзя объединить.")

        case "инфо":
            if arg in ITEMS_DB:
                print(f">> [{arg.upper()}]: {ITEMS_DB[arg]}")
            else:
                print(">> Информация о таком предмете отсутствует в базе данных.")

        case "взять":
            if arg == "ракетница" and current_lvl == 4 and player["infected"]:
                print(">> Отказ биометрии стойки: ОБНАРУЖЕНО ЗАРАЖЕНИЕ! Сначала вылечитесь в терминале.")
            elif arg in room_items:
                room_items.remove(arg)
                inventory.append(arg)
                print(f">> Предмет '{arg}' добавлен в ваш инвентарь.")
            else:
                print(f">> Предмета '{arg}' здесь нет.")

        case "выход":
            print(">> Выход из игры...")
            game_active = False

        case _:
            command_handled = False

    # --------------------------------------------------------------------------
    # БЛОК 2: СЮЖЕТНЫЕ КОМАНДЫ УРОВНЕЙ ЧЕРЕЗ SWITCH-CASE И IF / ELIF / ELSE
    # --------------------------------------------------------------------------
    if not command_handled and game_active:
        match current_lvl:
            # ==================== ЛОГИКА УРОВНЯ 1 ====================
            case 1:
                if cmd == "осмотреть":
                    print(f"\nПредметы в холле: {', '.join(room_items) if room_items else 'пусто'}")
                    if "медаль льва" in room_items:
                        print(">> Подсказка: 'медаль льва' лежит прямо на стойке администратора! (взять медаль льва)")
                    print("Объекты: памятка офицера, запертый стол, сейф в углу, статуя Богини.")
                    print("Введите 'действия' (или 'д') для просмотра точных команд.")
                elif cmd == "читать памятку":
                    print(">> Памятка: 'Код сейфа — год основания S.T.A.R.S. (1996) плюс 240 (итого 2236)'.")
                elif cmd == "обыскать стол":
                    if "стол" not in solved_puzzles:
                        print(">> Вы срываете замок ящика! Внутри 'медаль девы' (возьмите ее командой 'взять медаль девы').")
                        room_items.append("медаль девы")
                        solved_puzzles.add("стол")
                    else:
                        print(">> Стол уже обыскан и пуст.")
                elif cmd == "открыть сейф":
                    if "сейф" in solved_puzzles:
                        print(">> Сейф уже открыт.")
                    else:
                        code = input("Введите 4-значный код сейфа: ").strip()
                        if code == SECURITY_CODES["сейф"]:
                            print(">> Сейф открыт! Вы забрали в инвентарь 'медаль единорога' и 'зажигалка'.")
                            inventory.extend(["медаль единорога", "зажигалка"])
                            solved_puzzles.add("сейф")
                        else:
                            player["hp"] -= 15
                            print(f">> Неверный код! Электрошок защиты отнимает 15 HP (Осталось: {player['hp']} HP).")
                elif cmd == "вставить медали":
                    found = set(inventory).intersection(required_medals)
                    if not found:
                        print(">> В инвентаре нет ни одной медали.")
                    else:
                        for m in found:
                            inventory.remove(m)
                            inserted_medals.add(m)
                            print(f">> Вы вставили '{m}' в постамент статуи.")
                        print(f">> Установлено медалей: {len(inserted_medals)}/3.")
                        if required_medals.issubset(inserted_medals):
                            print(">> Статуя сдвигается, открывая тайный проход! Команда: 'идти дальше'.")
                            unlocked_doors.add("проход_1")
                elif cmd == "идти дальше":
                    if "проход_1" in unlocked_doors:
                        player["level"] = 2
                    else:
                        print(">> Проход закрыт! Сначала соберите и вставьте все 3 медали.")
                else:
                    print(">> Неизвестная команда. Введите 'действия' (или 'д') для подсказки.")

            # ==================== ЛОГИКА УРОВНЯ 2 ====================
            case 2:
                if cmd == "осмотреть":
                    print(f"\nПредметы в помещении: {', '.join(room_items) if room_items else 'пусто'}")
                    print(f"Враги в коридоре: {', '.join(enemies_lvl2) if enemies_lvl2 else 'все враги повержены'}")
                    print("Объекты: дневник на столе, оружейный шкафчик, 3 факела у решетки.")
                elif cmd == "читать дневник":
                    print(">> Дневник Вескера: 'Код от шкафчика с дробовиком — первые 3 буквы от CAPTAIN (CAP).")
                    print("   Порядок зажигания факелов: северный -> южный -> восточный'.")
                elif cmd == "открыть шкафчик":
                    if "шкафчик" in solved_puzzles:
                        print(">> Оружейный шкафчик уже пуст.")
                    else:
                        code = input("Введите 3-буквенный код шкафчика: ").strip().upper()
                        if code == SECURITY_CODES["шкафчик"]:
                            print(">> Замок открыт! Вы получили 'дробовик' и 'болтрез'!")
                            inventory.extend(["дробовик", "болтрез"])
                            solved_puzzles.add("шкафчик")
                        else:
                            print(">> Код не подошел.")
                elif cmd == "атаковать":
                    if not enemies_lvl2:
                        print(">> Коридор чист, атаковать некого.")
                    elif enemies_lvl2[0] == "зомби-полицейский":
                        enemies_lvl2.pop(0)
                        defeated_enemies.add("зомби-полицейский")
                        if "пистолет" in inventory and "патроны" in inventory:
                            inventory.remove("патроны")
                            print(">> Вы метко застрелили зомби из пистолета, потратив патроны!")
                        else:
                            player["hp"] -= 30
                            print(">> Без патронов пришлось биться врукопашную! Зомби укусил вас (-30 HP).")
                    elif enemies_lvl2[0] == "лизун":
                        if "дробовик" in inventory:
                            enemies_lvl2.pop(0)
                            defeated_enemies.add("лизун")
                            print(">> Мощный залп из дробовика убивает прыгнувшего Лизуна наповал!")
                        else:
                            player["hp"] -= 55
                            print(">> Без дробовика Лизун тяжело ранит вас когтями (-55 HP)! Откройте шкафчик!")
                elif cmd == "зажечь факелы":
                    if enemies_lvl2:
                        print(">> Слишком опасно! Сначала убейте всех врагов командой 'атаковать'.")
                    elif "зажигалка" not in inventory:
                        print(">> У вас нет зажигалки!")
                    else:
                        f1 = input("Факел #1 (северный/южный/восточный): ").strip().lower()
                        f2 = input("Факел #2 (северный/южный/восточный): ").strip().lower()
                        f3 = input("Факел #3 (северный/южный/восточный): ").strip().lower()
                        if [f1, f2, f3] == correct_torches:
                            print(">> Пламя вспыхивает! Магнитный замок отключен, решетка поднята!")
                            unlocked_doors.add("проход_2")
                        else:
                            player["hp"] -= 15
                            print(">> Неверный порядок! Ловушка обжигает вас огнем (-15 HP).")
                elif cmd == "идти дальше":
                    if "проход_2" in unlocked_doors:
                        player["level"] = 3
                    else:
                        print(">> Решетка закрыта! Зачистите врагов и зажгите факелы.")
                else:
                    print(">> Неизвестная команда. Введите 'действия' (или 'д') для подсказки.")

            # ==================== ЛОГИКА УРОВНЯ 3 ====================
            case 3:
                if cmd == "осмотреть":
                    print(f"\nПредметы вокруг: {', '.join(room_items) if room_items else 'пусто'}")
                    print("Объекты: записка инженера, контейнер в цепях, паровые трубы, сканер фуникулера.")
                elif cmd == "читать записку":
                    print(">> Записка: 'Переведите труба 1 и труба 3 в статус ВЫКЛ с помощью вентиля.")
                    print("   Для био-сканера используйте команду смешать (синяя колба + красная колба)'.")
                elif cmd == "срезать цепь":
                    if "цепь" in solved_puzzles:
                        print(">> Цепь уже срезана, контейнер пуст.")
                    elif "болтрез" in inventory:
                        print(">> Вы перекусили цепь болтрезом! Получены 'вентиль' и 'красная колба'.")
                        inventory.extend(["вентиль", "красная колба"])
                        solved_puzzles.add("цепь")
                    else:
                        print(">> Стальная цепь слишком прочная, нужен 'болтрез'.")
                elif cmd == "перекрыть пар":
                    if "вентиль" not in inventory:
                        print(">> Штурвала нет! Сначала достаньте 'вентиль' из контейнера с цепью.")
                    else:
                        for pipe_name, is_on in valves_lvl3.items():
                            print(f"  * {pipe_name}: {'ПАР ИДЕТ' if is_on else 'ВЫКЛ'}")
                        target_pipe = input("Какую трубу переключить? (труба 1 / труба 2 / труба 3): ").strip().lower()
                        if target_pipe in valves_lvl3:
                            valves_lvl3[target_pipe] = not valves_lvl3[target_pipe]
                            print(f">> Вы повернули вентиль на '{target_pipe}'.")
                            if not any(valves_lvl3.values()):
                                print(">> Подача пара полностью перекрыта! Путь к сканеру свободен.")
                                solved_puzzles.add("пар")
                        else:
                            print(">> Такой трубы не существует.")
                elif cmd == "сканировать":
                    if "пар" not in solved_puzzles:
                        player["hp"] -= 25
                        print(">> Вы получили ожоги от струи пара (-25 HP)! Сначала перекройте пар!")
                    elif "фиолетовая колба" in inventory:
                        print(">> Сканер подтвердил реагент! Двери фуникулера открыты (команда 'идти дальше').")
                        unlocked_doors.add("проход_3")
                    else:
                        print(">> Ошибка сканера: требуется 'фиолетовая колба' (используйте команду 'смешать').")
                elif cmd == "идти дальше":
                    if "проход_3" in unlocked_doors:
                        player["level"] = 4
                    else:
                        print(">> Двери фуникулера заблокированы.")
                else:
                    print(">> Неизвестная команда. Введите 'действия' (или 'д') для подсказки.")

            # ==================== ЛОГИКА УРОВНЯ 4 ====================
            case 4:
                if cmd == "осмотреть":
                    print(f"\nПредметы в зале (на стойке): {', '.join(room_items) if room_items else 'пусто'}")
                    if "ракетница" in room_items:
                        print(">> Подсказка: На стойке лежит 'ракетница'! Заберите ее: взять ракетница")
                    print("Объекты: научный терминал вакцины, Тиран Т-103 у шлюза, бронепоезд эвакуации.")
                elif cmd == "терминал":
                    if not player["infected"]:
                        print(">> Вы уже ввели вакцину и полностью здоровы.")
                    else:
                        correct_cnt = 0
                        for question, right_ans in quiz_lvl4.items():
                            user_ans = input(f"Вопрос: {question}\nОтвет: ").strip().lower()
                            if user_ans == right_ans:
                                correct_cnt += 1
                        if correct_cnt == len(quiz_lvl4):
                            player["infected"] = False
                            inventory.append("вакцина")
                            solved_puzzles.add("вакцина")
                            print(">> Код принят! Вы синтезировали и ввели себе вакцину. Заражение снято!")
                        else:
                            player["hp"] -= 20
                            print(">> Сбой авторизации! G-вирус отнимает 20 HP. Попробуйте еще раз.")
                elif cmd == "бой с тираном":
                    if not tyrant_alive:
                        print(">> Тиран Т-103 уже уничтожен.")
                    elif "ракетница" in inventory:
                        inventory.remove("ракетница")
                        tyrant_alive = False
                        defeated_enemies.add("тиран т-103")
                        print(">> ПРЯМОЕ ПОПАДАНИЕ! Заряд ракетницы разносит Тирана Т-103 на куски!")
                    else:
                        player["hp"] -= 50
                        print(">> Обычное оружие не берет Тирана! Он наносит вам удар (-50 HP). Нужна ракетница!")
                elif cmd == "эвакуация":
                    if tyrant_alive:
                        print(">> Тиран преграждает путь к бронепоезду! Уничтожьте его!")
                    elif player["infected"]:
                        print(">> Система безопасности поезда не пускает зараженных! Создайте вакцину в терминале.")
                    else:
                        print("\n" + "=" * 68)
                        print(f"ПОБЕДА! {player['name']} успешно покинул Раккун-Сити на бронепоезде!")
                        print(f"Остаток HP: {player['hp']} | Решено задач: {len(solved_puzzles)} | Боссы: {', '.join(defeated_enemies)}")
                        print("=" * 68)
                        game_active = False
                else:
                    print(">> Неизвестная команда. Введите 'действия' (или 'д') для подсказки.")

