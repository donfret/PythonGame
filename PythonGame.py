def level_2_office():
    show_status()
    print("СЮЖЕТ: В коридоре монстры, а путь на парковку закрыт решеткой с магнитным замком.")
    print("Найдите оружие, зачистите коридор и зажгите 3 факела в правильном порядке.")

    room_items = ["зеленая трава", "патроны"]
    enemies = ["зомби-полицейский", "лизун"]
    correct_torches = ["северный", "южный", "восточный"]

    while True:
        check_alive()
        cmd = input("\n[Уровень 2 - Офис] Команда: ").strip().lower()
        if process_base_command(cmd, room_items):
            continue

        if cmd == "осмотреть":
            print(f"\nПредметы: {', '.join(room_items) if room_items else 'пусто'}")
            print(f"Враги на пути: {', '.join(enemies) if enemies else 'все уничтожены'}")
            print("Введите 'действия' (или 'д'), чтобы посмотреть список доступных команд.")
            if "проход_2" in unlocked_doors:
                print("Решетка поднята! Введите [идти дальше] для спуска в канализацию.")
        elif cmd == "читать дневник":
            print(">> Дневник Вескера: 'Код оружейного шкафчика — первые три буквы слова CAPTAIN (CAP).")
            print("   Замок решетки: зажгите факелы в порядке: северный -> южный -> восточный'.")
        elif cmd == "открыть шкафчик":
            if "шкафчик" in solved_puzzles:
                print(">> Шкафчик уже пуст.")
            elif input("Введите 3-буквенный код: ").strip().upper() == SECURITY_CODES["шкафчик"]:
                print(">> Вы открыли шкафчик и забрали 'дробовик' и 'болтрез'!")
                inventory.extend(["дробовик", "болтрез"])
                solved_puzzles.add("шкафчик")
            else:
                print(">> Неверный код.")
        elif cmd == "атаковать":
            if not enemies:
                print(">> Все враги здесь уже повержены.")
            elif enemies[0] == "зомби-полицейский":
                enemies.pop(0)
                defeated_enemies.add("зомби-полицейский")
                if "пистолет" in inventory and "патроны" in inventory:
                    inventory.remove("патроны")
                    print(">> Вы застрелили зомби из пистолета, потратив обойму патронов!")
                else:
                    player["hp"] -= 30
                    print(">> Нет патронов! Вы убили зомби врукопашную, но он укусил вас (-30 HP).")
            elif enemies[0] == "лизун":
                if "дробовик" in inventory:
                    enemies.pop(0)
                    defeated_enemies.add("лизун")
                    print(">> Выстрел из дробовика убивает прыгнувшего Лизуна наповал!")
                else:
                    player["hp"] -= 55
                    print(">> Без дробовика Лизун тяжело ранит вас (-55 HP)! Откройте шкафчик!")
        elif cmd == "зажечь факелы":
            if enemies:
                print(">> Сначала уничтожьте врагов в коридоре (команда 'атаковать')!")
            elif "зажигалка" not in inventory:
                print(">> У вас нет зажигалки!")
            else:
                order = [input(f"Факел #{i} (северный/южный/восточный): ").strip().lower() for i in range(1, 4)]
                if order == correct_torches:
                    print(">> Порядок верный! Магнитный замок отключен, решетка поднята!")
                    unlocked_doors.add("проход_2")
                else:
                    player["hp"] -= 15
                    print(">> Ошибка последовательности! Вспышка пламени обжигает вас (-15 HP).")
        elif cmd == "идти дальше" and "проход_2" in unlocked_doors:
            player["level"] = 3
            break
        else:
            print(">> Неизвестная команда или проход закрыт. Введите 'осмотреть' или 'действия'.")


