def level_3_sewers():
    show_status()
    print("СЮЖЕТ: Проход к фуникулеру прегражден паром из прорванных труб.")
    print("Перекройте пар вентилем и смешайте реагенты в 'фиолетовая колба' для сканера.")

    room_items = ["синяя колба", "зеленая трава"]
    valves = {"труба 1": True, "труба 2": False, "труба 3": True}

    while True:
        check_alive()
        cmd = input("\n[Уровень 3 - Канализация] Команда: ").strip().lower()
        if process_base_command(cmd, room_items):
            continue

        if cmd == "осмотреть":
            print(f"\nПредметы: {', '.join(room_items) if room_items else 'пусто'}")
            print("Введите 'действия' (или 'д'), чтобы посмотреть список доступных команд.")
            if "проход_3" in unlocked_doors:
                print("Фуникулер открыт! Введите [идти дальше] для поездки в лабораторию.")
        elif cmd == "читать записку":
            print(">> Записка: 'Переведите труба 1 и труба 3 в статус ВЫКЛ с помощью вентиля.")
            print("   Для био-сканера используйте команду смешать (синяя колба + красная колба)'.")
        elif cmd == "срезать цепь":
            if "цепь" in solved_puzzles:
                print(">> Контейнер уже вскрыт.")
            elif "болтрез" in inventory:
                print(">> Цепь срезана! Внутри найдены 'вентиль' и 'красная колба'.")
                inventory.extend(["вентиль", "красная колба"])
                solved_puzzles.add("цепь")
            else:
                print(">> Вам нужен 'болтрез'.")
        elif cmd == "перекрыть пар":
            if "вентиль" not in inventory:
                print(">> Нужен 'вентиль'! Вскройте контейнер командой 'срезать цепь'.")
                continue
            for k, v in valves.items():
                print(f"  * {k}: {'ПАР ИДЕТ' if v else 'ВЫКЛ'}")
            pipe = input("Какую трубу переключить? (труба 1 / труба 2 / труба 3): ").strip().lower()
            if pipe in valves:
                valves[pipe] = not valves[pipe]
                print(f">> Вентиль на '{pipe}' повернут.")
                if not any(valves.values()):
                    print(">> Все трубы перекрыты! Паровая завеса исчезла!")
                    solved_puzzles.add("пар")
            else:
                print(">> Такой трубы нет.")
        elif cmd == "сканировать":
            if "пар" not in solved_puzzles:
                player["hp"] -= 25
                print(">> Вы обожглись паром (-25 HP)! Сначала перекройте пар!")
            elif "фиолетовая колба" in inventory:
                print(">> Реагент подтвержден! Двери фуникулера открыты!")
                unlocked_doors.add("проход_3")
            else:
                print(">> Нужна 'фиолетовая колба' (используйте команду 'смешать').")
        elif cmd == "идти дальше" and "проход_3" in unlocked_doors:
            player["level"] = 4
            break
        else:
            print(">> Неизвестная команда или двери закрыты. Введите 'осмотреть' или 'действия'.")


