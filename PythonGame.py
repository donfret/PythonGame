def heal_player():
    if "аптечка" in inventory:
        inventory.remove("аптечка")
        player["hp"] = player["max_hp"]
        print(">> Вы использовали аптечку. Здоровье полностью восстановлено (100 HP)!")
    elif "зеленая трава" in inventory:
        inventory.remove("зеленая трава")
        player["hp"] = min(player["max_hp"], player["hp"] + 35)
        print(f">> Вы использовали зеленую траву. Здоровье: {player['hp']} HP.")
    else:
        print(">> В инвентаре нет лечебных трав или аптечки.")


def craft_items():
    print("Ваш инвентарь:", ", ".join(inventory))
    item1 = input("Первый предмет для смешивания: ").strip().lower()
    item2 = input("Второй предмет для смешивания: ").strip().lower()
    if item1 not in inventory or item2 not in inventory or item1 == item2:
        print(">> Ошибка: нужны два разных предмета из вашего инвентаря.")
        return
    recipe_key = tuple(sorted([item1, item2]))
    if recipe_key in CRAFT_RECIPES:
        result = CRAFT_RECIPES[recipe_key]
        inventory.remove(item1)
        inventory.remove(item2)
        inventory.append(result)
        print(f">> УСПЕХ! Вы объединили предметы и получили: '{result}'!")
    else:
        print(">> Эти предметы нельзя скомбинировать.")


def check_alive():
    if player["hp"] <= 0:
        print_line()
        print("ВЫ ПОГИБЛИ... Кошмар Раккун-Сити поглотил вас. ИГРА ОКОНЧЕНА.")
        sys.exit()


def process_base_command(cmd, room_items):
    if cmd == "помощь":
        show_help()
    elif cmd in ("действия", "д"):
        show_current_actions()
    elif cmd == "статус":
        show_status()
    elif cmd == "лечиться":
        heal_player()
    elif cmd == "смешать":
        craft_items()
    elif cmd == "выход":
        print("Игра завершена.")
        sys.exit()
    elif cmd.startswith("инфо "):
        item = cmd[5:].strip()
        print(f">> [{item.upper()}]: {ITEMS_DB.get(item, 'Предмет неизвестен.')}")
    elif cmd.startswith("взять "):
        item = cmd[6:].strip()
        # Специальная проверка на заражение при попытке взять ракетницу на 4 уровне
        if item == "ракетница" and player["level"] == 4 and player["infected"]:
            print(
                ">> Биометрический замок стойки блокирует доступ: ОБНАРУЖЕНО ЗАРАЖЕНИЕ! Сначала вылечитесь в терминале.")
            return True
        if item in room_items:
            room_items.remove(item)
            inventory.append(item)
            print(f">> Предмет '{item}' добавлен в инвентарь.")
        else:
            print(f">> Предмета '{item}' здесь нет.")
    else:
        return False
    return True


